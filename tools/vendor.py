"""Download the UI's fonts and icons into agentboard/web/vendor (run once; the app never fetches at runtime).

Fonts: Geist and Geist Mono (SIL Open Font License). Icons: Phosphor regular (MIT).
"""
import json
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "agentboard", "web", "vendor")
CDN = "https://cdn.jsdelivr.net/npm"
GEIST = "geist@1.8.1"
PHOSPHOR = "@phosphor-icons/core@2.1.1"
ICONS = ["push-pin", "push-pin-slash", "gear-six", "minus", "x", "terminal-window", "app-window", "code",
         "arrow-up-right", "chart-donut", "stack", "warning-circle", "hand", "cpu", "sun", "moon", "caret-right",
         "corners-out", "corners-in", "kanban", "columns", "rows"]


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "agentboard-vendor"}), timeout=60) as r:
        return r.read()


def main():
    os.makedirs(os.path.join(OUT, "fonts"), exist_ok=True)
    for src, name in ((f"{GEIST}/dist/fonts/geist-sans/Geist-Variable.woff2", "Geist-Variable.woff2"),
                      (f"{GEIST}/dist/fonts/geist-mono/GeistMono-Variable.woff2", "GeistMono-Variable.woff2")):
        open(os.path.join(OUT, "fonts", name), "wb").write(fetch(f"{CDN}/{src}"))
    open(os.path.join(OUT, "LICENSE-geist.txt"), "wb").write(fetch(f"{CDN}/{GEIST}/LICENSE.txt"))
    open(os.path.join(OUT, "LICENSE-phosphor.txt"), "wb").write(fetch(f"{CDN}/{PHOSPHOR}/LICENSE"))
    icons = {}
    for name in ICONS:
        svg = fetch(f"{CDN}/{PHOSPHOR}/assets/regular/{name}.svg").decode("utf-8").strip()
        icons[name] = svg.replace('fill="#000000"', 'fill="currentColor"')
    with open(os.path.join(OUT, "icons.js"), "w", encoding="utf-8") as f:
        f.write("// Phosphor Icons (regular), MIT licence. Generated by tools/vendor.py; do not edit.\n")
        f.write("window.ICONS = " + json.dumps(icons, indent=1) + ";\n")
    print("vendored", len(icons), "icons and 2 fonts into", OUT)


if __name__ == "__main__":
    main()
